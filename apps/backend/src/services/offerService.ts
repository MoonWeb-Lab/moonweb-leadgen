import { config } from '../config.js';

export interface LeadOfferData {
  id: number;
  name: string;
  cityName: string;
  categoryName?: string;
  subcategoryId?: string;
  phonePrimary?: string;
  instagram?: string;
  rating?: number;
}

export function generateOffer(lead: LeadOfferData) {
  // Strip duplicate quotes and normalize
  const cleanName = lead.name.replace(/«([^»]+)»/g, '$1').replace(/["']/g, '').trim();
  const city = lead.cityName || 'вашем городе';
  const subcat = lead.subcategoryId || '';
  const studioTg = `@${config.studio.telegram}`;
  const studioInst = `@${config.studio.instagram}`;

  let pitch = '';
  let keyHooks: string[] = [];
  let suggestedAction = 'Отправить в Telegram или Instagram Direct';

  // 1. HoReCa и Общепит (Кофейни, бистро, рестораны, доставка)
  if (subcat === 'coffee' || subcat === 'bistro' || subcat === 'restaurants' || subcat === 'bakery' || subcat === 'food_delivery') {
    keyHooks = [
      'Гости за столиками сканируют QR-код и сразу видят сочные фото блюд со смартфона',
      'Бронь столиков и предзаказ навынос без долгих переписок в Директе',
      'Сезонные спешлы и стоп-лист обновляются за 30 секунд'
    ];
    pitch = 
`Привет, команда «${cleanName}»! ☕

Мы команда веб-студии MoonWeb Lab. Любим атмосферные заведения и с удовольствием следим за вашим развитием в ${city}.

Обратили внимание на важный момент: ваши гости сейчас вынуждены выискивать меню и цены по сторис и хайлайтсам в Инстаграме. Из-за этого многие уходят к конкурентам, где меню открывается в один клик.

Мы создаем для кафе и ресторанов стильные мобильные сайты:
1. Интерактивное меню со смартфона (гость за столом наводит камеру на QR-код и сразу видит аппетитные фото блюд и составы).
2. Кнопка быстрой брони столика и предзаказ кофе/еды с собой прямо в ваш Telegram.
3. Карта ваших локаций и часы работы, чтобы гости легко строили маршрут.

Наш свежий живой проект для бистро можно оценить здесь: ${config.studio.portfolioUrl}

Подскажите, есть в планах сделать удобное онлайн-меню для заведения? Будем рады познакомиться и набросать пару классных идей для «${cleanName}»! Наш ТГ: ${studioTg} / Инста: ${studioInst}`;
  }

  // 2. Бьюти, Салоны красоты, Барбершопы
  else if (subcat === 'barbershop' || subcat === 'beauty_salon' || subcat === 'nails' || subcat === 'brows_lashes' || subcat === 'massage_spa') {
    keyHooks = [
      'Клиент записывается в 2 клика 24/7, даже ночью, когда администратор спит',
      'Прозрачный прайс-лист и работы конкретных мастеров на одном экране',
      '0 потерянных клиентов из-за долгого ответа в Директе'
    ];
    pitch =
`Здравствуйте! Очень приятная атмосфера и классные работы мастеров у «${cleanName}» ✨

Мы команда веб-студии MoonWeb Lab. Заметили, что у вас в ${city} сильный поток клиентов, но всю запись и консультации приходится вести вручную через сообщения.

В бьюти-сфере до 30% клиентов отваливаются просто потому, что не дождались ответа администратора в Директе или постеснялись переспрашивать прайс.

Мы делаем для студий красоты и барбершопов легкие сайты-визитки:
— Прозрачный прайс с разделением по категориям (чтобы клиенты не переспрашивали цены);
— Галерея работ мастеров и сертификатов;
— Удобная онлайн-запись в 2 клика прямо в ваш рабочий мессенджер.

Посмотреть наши работы можно в профиле или на сайте: ${config.studio.portfolioUrl}

Думали запустить для студии современную онлайн-визитку, чтобы разгрузить администратора? Напишите нам в Telegram: ${studioTg} или Instagram: ${studioInst}`;
  }

  // 3. Автобизнес: Детейлинг, оклейка, мойки, СТО
  else if (subcat === 'detailing' || subcat === 'carwash' || subcat === 'tire_service' || subcat === 'autoservice' || subcat === 'body_repair') {
    keyHooks = [
      'Калькулятор расчета стоимости оклейки/полировки под конкретный класс авто',
      'Интерактивные слайдеры «До / После» по кузову и салону',
      'Готовые горячие заявки с номером телефона сразу мастеру'
    ];
    pitch =
`Привет, команда «${cleanName}»! 👋

Мы из веб-студии MoonWeb Lab. Отличный уровень работ в ленте — видно, что относитесь к автомобилям с педантичностью и вниманием к мелочам 👍

Обратили внимание, что в ${city} вы ведете запись в основном через звонки и Директ. В автобизнесе и детейлинге владельцы авто не любят долгие переписки с вопросами «а сколько стоит затянуть капот на Geely/BMW» и «что входит в комплекс».

Мы внедряем для студий автоухода стильные темные сайты-портфолио:
• Наглядные интерактивные слайдеры «До / После» (по полировке кузова и химчистке салона);
• Простой калькулятор стоимости под класс авто (седан, кроссовер, внедорожник);
• Заявка с маркой авто и номером клиента падает сразу мастеру в Telegram.

Наши кейсы можно глянуть тут: ${config.studio.portfolioUrl}

Рассматривали запуск сайта для студии, чтобы привлекать больше премиальных авто? Наш Telegram: ${studioTg} / Instagram: ${studioInst}`;
  }

  // 4. Кухни, мебель на заказ, ремонт квартир
  else if (subcat === 'kitchens' || subcat === 'apartment_renovation' || subcat === 'stretch_ceilings' || subcat === 'interior_design' || subcat === 'bathhouse_build') {
    keyHooks = [
      'Квиз-калькулятор «Узнайте стоимость за 1 минуту по вашим размерам»',
      'Отсекает пустые переписки «сколько стоит за погонный метр»',
      'Замерщик получает готовый проект с планировкой и телефоном'
    ];
    pitch =
`Добрый день! Отличные проекты и качество сборки у «${cleanName}» 👍

Мы команда веб-студии MoonWeb Lab. Заметили, что у вас в ${city} классное портфолио, но потенциальные клиенты в комментариях постоянно задают одни и те же вопросы: «а сколько за погонный метр?» и «сколько выйдет вот такая как на фото?».

Чтобы не тратить часы замерщиков на пустые созвоны, мы делаем для мебельщиков и строителей квиз-лендинги с высокой конверсией:
1. Клиент на сайте за 1 минуту отвечает на 4 простых вопроса (форма, материалы, ориентировочные размеры и бюджет);
2. Замерщику в Telegram падает готовая заявка с параметрами и телефоном клиента;
3. Человек уже понимает вилку цен и готов к замеру.

Один закрытый договор с такого сайта окупает разработку в разы. Наши кейсы: ${config.studio.portfolioUrl}

Интересно глянуть, как такой инструмент можно запустить под вашу мебель? Напишите нам в Telegram: ${studioTg} или Instagram: ${studioInst}`;
  }

  // 5. Загородный отдых, усадьбы, бани, глэмпинги
  else if (subcat === 'agrotourism' || subcat === 'saunas_baths' || subcat === 'glamping' || subcat === 'cottages_rent' || subcat === 'recreation_centers') {
    keyHooks = [
      '100% внимания гостя принадлежит вашей усадьбе (нет рекламы соседей как на каталогах)',
      'Наглядный онлайн-календарь свободных дат — меньше 50 пустых звонков в день',
      'Прямое бронирование без посредников и комиссий'
    ];
    pitch =
`Здравствуйте! Очень красивая локация и усадьба «${cleanName}» 🌲

Мы из веб-студии MoonWeb Lab. Заметили, что вы размещаетесь на общих досках и в соцсетях, но своего независимого сайта нет.

Главная проблема агрегаторов и каталогов — прямо под вашим домом гостям показывают десятки чужих усадеб по соседству с ценником ниже, и часть гостей неизбежно уходит к конкурентам.

Мы разрабатываем для загородных домов и бань персональные сайты:
🌲 Всё внимание гостя отдано только вашим домам и фото территории;
📅 Интерактивный календарь свободных дат (гости сразу видят свободные выходные);
🔥 Галерея бани, чана и спальни + кнопка моментальной брони напрямую вам в Telegram/Viber без комиссий.

Наше портфолио в профиле или по ссылке: ${config.studio.portfolioUrl}

Думали уйти от зависимости от каталогов и запустить свой сайт с календарем? Будем рады пообщаться! Telegram: ${studioTg} / Instagram: ${studioInst}`;
  }

  // 6. Универсальный человечный шаблон для других ниш
  else {
    keyHooks = [
      'Сайт привлекает клиентов из поиска Яндекс и Google по городу',
      'Быстрый расчет услуг и кнопка связи в 1 клик',
      'Повышение доверия и среднего чека компании'
    ];
    pitch =
`Добрый день, команда «${cleanName}»! 👋

Мы команда веб-студии MoonWeb Lab. Обратили внимание, что у вашего бизнеса в ${city} отличный потенциал и репутация, но своего официального сайта пока нет.

Сейчас большинство платежеспособных клиентов перед заказом ищут компанию в поиске Яндекс/Google, чтобы увидеть цены, гарантии и реальные фото. Без сайта часть этих обращений уходит конкурентам.

Мы создаем современные, быстрые сайты под ключ: с удобной мобильной версией, каталогом услуг и прямыми кнопками заявки в Telegram и звонка.

Посмотреть наши живые работы можно по ссылке: ${config.studio.portfolioUrl}

Подскажите, актуален ли для вас вопрос запуска сайта в ближайшее время? Напишите нам в Telegram: ${studioTg} или Instagram: ${studioInst} — покажем свежие идеи!`;
  }

  return {
    leadId: lead.id,
    businessName: lead.name,
    city: lead.cityName,
    niche: lead.categoryName || 'Бизнес',
    messageText: pitch,
    keyHooks,
    suggestedAction
  };
}
