export interface PitchConfig {
  studioName: string;
  studioTelegram: string;
  studioInstagram: string;
  portfolioUrl: string;
}

export const DEFAULT_PITCH_CONFIG: PitchConfig = {
  studioName: 'MoonWeb Lab',
  studioTelegram: 'moonweb_lab',
  studioInstagram: 'moonweb_labs',
  portfolioUrl: 'https://moonweb-lab.github.io/moonweb-lab/',
};

export interface GeneratedPitch {
  pitchText: string;
  keyHooks: string[];
  suggestedAction: string;
}

export function buildHumanizedPitch(
  businessName: string,
  cityName: string,
  subcategoryId: string = '',
  cfg: PitchConfig = DEFAULT_PITCH_CONFIG
): GeneratedPitch {
  const cleanName = businessName.replace(/«([^»]+)»/g, '$1').replace(/["']/g, '').trim();
  const city = cityName || 'вашем городе';
  const subcat = (subcategoryId || '').toLowerCase();
  const tgHandle = `@${cfg.studioTelegram.replace(/^@/, '')}`;
  const instHandle = `@${cfg.studioInstagram.replace(/^@/, '')}`;

  // 1. HoReCa и Общепит (кофейни, рестораны, бистро, пекарни, доставка)
  if (
    subcat.includes('coffee') ||
    subcat.includes('bistro') ||
    subcat.includes('restaurant') ||
    subcat.includes('bakery') ||
    subcat.includes('food') ||
    subcat.includes('horeca')
  ) {
    return {
      keyHooks: [
        'QR-меню за столиками: сочные фото блюд со смартфона за 1 секунду',
        'Предзаказ навынос и бронь столиков без звонков прямо в ваш Telegram',
        'Быстрое обновление стоп-листа и сезонных цен за 30 секунд',
      ],
      suggestedAction: 'Отправить в Telegram или Instagram Direct заведения',
      pitchText:
`Привет, команда «${cleanName}»! ☕

Мы из веб-студии MoonWeb Lab. Следим за вашим заведением в ${city} — подача и визуал блюд отличные 👍

Обратили внимание, что у вас нет своего онлайн-меню со смартфона: гостям приходится выискивать блюда и цены в сторис или актуальных в Инстаграме. Из-за этого часть людей закрывает профиль и уходит туда, где меню открывается сразу в один клик.

Мы делаем для заведений быстрые мобильные сайты за 3–5 дней:
— Гость сканирует QR-код за столиком и сразу видит меню с фото и составом;
— Предзаказ навынос или бронь столика прилетает прямо в ваш Telegram;
— Цены и стоп-лист вы меняете сами за пару секунд со смартфона.

Посмотрите наше живое демо со смартфона: https://moonweb-lab.github.io/botanica-bistro/

Думали запустить для заведения удобное онлайн-меню? Напишите нам в Telegram (${tgHandle}) или Instagram (${instHandle}) — покажем, как это будет выглядеть под ваши блюда.`,
    };
  }

  // 2. Бьюти, Салоны красоты, Барбершопы, Косметология
  if (
    subcat.includes('barber') ||
    subcat.includes('beauty') ||
    subcat.includes('hair') ||
    subcat.includes('nail') ||
    subcat.includes('brow') ||
    subcat.includes('lash') ||
    subcat.includes('massage') ||
    subcat.includes('spa')
  ) {
    return {
      keyHooks: [
        'Клиент сам выбирает мастера и свободное окно за 30 секунд',
        'Честный понятный прайс на одном экране без лишних вопросов в переписке',
        'Заявка с именем и телефоном сразу прилетает администратору в Telegram',
      ],
      suggestedAction: 'Отправить в Direct студии или мастеру в мессенджер',
      pitchText:
`Здравствуйте! Очень аккуратные работы мастеров у «${cleanName}» в ${city} ✨

Мы команда веб-студии MoonWeb Lab. Заметили, что запись и консультации у вас сейчас идут в основном через переписки в Директе. В бьюти-сфере до 30% клиентов отваливаются, если администратор не ответил за 10–15 минут или человеку лень переспрашивать прайс.

Мы собираем для студий красоты и барбершопов легкие сайты с онлайн-записью за 3–5 дней:
— Понятный прайс по категориям и карточки мастеров с примерами работ;
— Клиент в два клика выбирает нужное окно со смартфона в любое время суток;
— Готовая запись сразу падает вам в рабочий Telegram без долгой переписки.

Живой пример нашего проекта для барбершопа: https://moonweb-lab.github.io/blade-and-timber/

Рассматривали подключение онлайн-записи со смартфона, чтобы разгрузить администратора? Будем рады пообщаться в Telegram: ${tgHandle}`,
    };
  }

  // 3. Автобизнес: Детейлинг, оклейка, мойки, СТО
  if (
    subcat.includes('detail') ||
    subcat.includes('auto') ||
    subcat.includes('car') ||
    subcat.includes('wash') ||
    subcat.includes('tire')
  ) {
    return {
      keyHooks: [
        'Наглядные слайдеры «До / После» по полировке и химчистке',
        'Понятный расчет стоимости под конкретный класс авто',
        'Заявка с маркой машины и телефоном сразу мастеру в Telegram',
      ],
      suggestedAction: 'Отправить в рабочий Telegram или WhatsApp автостудии',
      pitchText:
`Привет, команда «${cleanName}»! 👋

Мы из студии MoonWeb Lab. Отличный уровень работ по автомобилям в ${city} — видно, что относитесь к процессу с педантичностью 👍

Заметили, что своего сайта у вас нет, а запись идёт через звонки и соцсети. Владельцам хороших машин часто некогда долго переписываться в Директе, чтобы узнать вилку цен на полировку, бронеплёнку или химчистку под свою модель.

Мы разрабатываем для автостудий стильные тёмные сайты-портфолио за 3–5 дней:
— Интерактивные слайдеры «До / После» по кузову и салону;
— Понятная сетка цен по классам авто (седан, кроссовер, внедорожник);
— Заявка с маркой авто и номером клиента падает напрямую мастеру в Telegram.

Посмотреть наши проекты можно здесь: https://moonweb-lab.github.io/moonweb-lab/

Думали упаковать студию в солидный сайт-портфолио? Наш Telegram: ${tgHandle}`,
    };
  }

  // 4. Мебель на заказ, кухни, ремонт квартир
  if (
    subcat.includes('kitchen') ||
    subcat.includes('furniture') ||
    subcat.includes('renovat') ||
    subcat.includes('repair') ||
    subcat.includes('ceiling') ||
    subcat.includes('design')
  ) {
    return {
      keyHooks: [
        'Квиз-расчет за 1 минуту отсекает пустые вопросы «сколько за метр»',
        'Замерщик получает готовый проект с параметрами и телефоном',
        'Один закрытый договор с сайта окупает разработку сразу',
      ],
      suggestedAction: 'Отправить владельцу мебельного производства или прорабу',
      pitchText:
`Добрый день! Качественные проекты и сборка у «${cleanName}» 👍

Мы из веб-студии MoonWeb Lab. Обратили внимание, что в ${city} вы привлекаете клиентов через соцсети, но отдельного сайта с расчетом пока нет.

Обычно мебельщикам и отделочникам приходится тратить уйму времени на пустые переписки в духе «а сколько стоит погонный метр?» и созвоны с теми, у кого ещё нет бюджета.

Мы внедряем для таких ниш понятные квиз-лендинги за 5–7 дней:
— Клиент за 1 минуту выбирает конфигурацию, материалы и ориентировочные размеры;
— Замерщик получает в Telegram готовую горячую заявку с параметрами и телефоном;
— На замер выезжаете только к тем, кто действительно готов заказывать.

Примеры наших работ: https://moonweb-lab.github.io/moonweb-lab/

Интересно глянуть, как такой инструмент может работать под ваши проекты? Наш Telegram: ${tgHandle}`,
    };
  }

  // 5. Загородный отдых, усадьбы, бани, глэмпинг, коттеджи
  if (
    subcat.includes('agro') ||
    subcat.includes('estate') ||
    subcat.includes('sauna') ||
    subcat.includes('bath') ||
    subcat.includes('glamp') ||
    subcat.includes('camp') ||
    subcat.includes('cottage')
  ) {
    return {
      keyHooks: [
        '100% внимания гостя только вашей усадьбе без рекламы конкурентов вокруг',
        'Онлайн-календарь свободных дат убирает десятки пустых звонков в день',
        'Прямое бронирование без посредников и комиссий агрегаторам',
      ],
      suggestedAction: 'Отправить владельцу усадьбы или администратору в Telegram/Viber',
      pitchText:
`Здравствуйте! Очень красивая локация и усадьба «${cleanName}» 🌲

Мы команда веб-студии MoonWeb Lab. Заметили, что вы размещаетесь на общих досках объявлений и в каталогах, но своего независимого сайта нет.

Главный минус каталогов — прямо под вашим домом гостям показывают соседние варианты конкурентов с ценником ниже, плюс приходится отдавать комиссии сервисам.

Мы делаем для загородного отдыха персональные сайты:
— Всё внимание гостя отдано только вашим домам и фото территории;
— Наглядный онлайн-календарь занятости (гости сразу видят открытые даты и не обрывают телефон вопросами);
— Прямая бронь без комиссий сразу вам в Telegram или Viber.

Наше портфолио: https://moonweb-lab.github.io/moonweb-lab/

Думали запустить свой сайт с календарем свободных дат? Будем рады пообщаться в Telegram: ${tgHandle}`,
    };
  }

  // 6. Универсальный честный оффер для остальных ниш
  return {
    keyHooks: [
      'Сайт привлекает клиентов из поиска Яндекс и Google по городу',
      'Быстрый выбор услуг и кнопка связи в 1 клик со смартфона',
      'Заявки с контактами приходят прямо вам в Telegram',
    ],
    suggestedAction: 'Отправить в Telegram, WhatsApp или Direct компании',
    pitchText:
`Добрый день, команда «${cleanName}»! 👋

Мы команда веб-студии MoonWeb Lab. Обратили внимание, что у вашего бизнеса в ${city} отличная репутация и отзывы, но официального сайта со смартфона пока нет.

Когда люди ищут услугу на картах или в поиске Яндекс/Google, 8 из 10 смотрят сайт, чтобы быстро увидеть цены, фото и понять, кому звонить. Если сайта нет — часть клиентов уходит тем, у кого всё расписано на одной странице.

Мы собираем быстрые, аккуратные сайты под задачи бизнеса за 3–5 дней: понятный каталог услуг, цены, кнопка звонка в один тап и отправка заявки вам в Telegram.

Наши проекты можно оценить по ссылке: ${cfg.portfolioUrl}

Подскажите, актуален ли для вас запуск понятного сайта в ближайшее время? Напишите нам в Telegram (${tgHandle}) — обсудим без лишней спешки.`,
  };
}
