import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';
import { db } from './engine.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const targetFile = path.resolve(__dirname, '../../../../apps/webapp/src/data/staticLeads.ts');

export function syncDatabaseToStaticLeads(): void {
  const leads = db.prepare(`
    SELECT 
      l.id,
      l.external_id as externalId,
      l.country_id as countryId,
      l.city_id as cityId,
      COALESCE(c.name, l.address) as cityName,
      l.subcategory_id as subcategoryId,
      sub.name as subcategoryName,
      sub.category_id as categoryId,
      cat.name as categoryName,
      cat.emoji as categoryEmoji,
      l.name,
      l.address,
      l.lat,
      l.lon,
      l.rating,
      l.reviews_count as reviewsCount,
      l.phone_primary as phonePrimary,
      l.instagram,
      l.telegram,
      l.source,
      l.has_real_website as hasRealWebsiteInt,
      l.raw_website as rawWebsite,
      l.crm_status as crmStatus
    FROM leads l
    LEFT JOIN cities c ON l.city_id = c.id
    LEFT JOIN subcategories sub ON l.subcategory_id = sub.id
    LEFT JOIN categories cat ON sub.category_id = cat.id
    ORDER BY l.reviews_count DESC, l.id ASC
  `).all() as any[];

  const formatted = leads.map(l => {
    const phoneClean = (l.phonePrimary || '').replace(/[^0-9]/g, '');
    const tgLink = l.telegram 
      ? `https://t.me/${l.telegram.replace(/^@/, '')}`
      : (phoneClean ? `https://t.me/+${phoneClean}` : undefined);

    const viberLink = phoneClean ? `viber://chat?number=%2B${phoneClean}` : undefined;
    const phoneLink = phoneClean ? `tel:+${phoneClean}` : undefined;

    return {
      id: l.id,
      externalId: l.externalId,
      countryId: l.countryId,
      cityId: l.cityId,
      cityName: l.cityName || 'Минск',
      subcategoryId: l.subcategoryId,
      subcategoryName: l.subcategoryName || 'Общее',
      categoryId: l.categoryId || 'horeca',
      categoryName: l.categoryName || 'Бизнес',
      categoryEmoji: l.categoryEmoji || '🏢',
      name: l.name,
      address: l.address || '',
      lat: l.lat || undefined,
      lon: l.lon || undefined,
      rating: l.rating || 0,
      reviewsCount: l.reviewsCount || 0,
      phonePrimary: l.phonePrimary || '',
      instagram: l.instagram || '',
      telegram: l.telegram || '',
      source: l.source || 'manual',
      hasRealWebsite: Boolean(l.hasRealWebsiteInt === 1),
      rawWebsite: l.rawWebsite || '',
      crmStatus: l.crmStatus || 'new',
      tgLink,
      viberLink,
      phoneLink,
    };
  });

  const content = `// Auto-generated by MoonWeb LeadGen Parser Sync\nexport const STATIC_LEADS = ${JSON.stringify(formatted, null, 2)};\n`;

  fs.writeFileSync(targetFile, content, 'utf-8');
  console.log(`[Sync] Успешно синхронизировано ${formatted.length} лидов в ${targetFile}`);
}

if (process.argv[1] && process.argv[1].endsWith('syncToStatic.ts')) {
  syncDatabaseToStaticLeads();
}
