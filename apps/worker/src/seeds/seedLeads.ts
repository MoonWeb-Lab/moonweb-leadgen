export function runSeed() {
  console.log(`=======================================================`);
  console.log(`🌱 Запуск наполнения тестовой базы (Минск & Могилёв)...`);
  console.log(`=======================================================`);

  const insertStmt = db.prepare(`
    INSERT OR REPLACE INTO leads (
      external_id, country_id, city_id, subcategory_id, name, address,
      lat, lon, rating, reviews_count, raw_website, has_real_website,
      phone_primary, instagram, telegram, vk, source
    ) VALUES (
      ?, ?, ?, ?, ?, ?,
      ?, ?, ?, ?, ?, ?,
      ?, ?, ?, ?, ?
    )
  `);

  let added = 0;
  for (const l of SEED_LEADS) {
    try {
      insertStmt.run(
        l.externalId, l.countryId, l.cityId, l.subcategoryId, l.name, l.address,
        l.lat, l.lon, l.rating, l.reviewsCount, l.rawWebsite, l.hasRealWebsite,
        l.phonePrimary, l.instagram, l.telegram, l.vk, l.source
      );
      added++;
    } catch (e: any) {
      console.error(`Ошибка при добавлении ${l.name}:`, e.message);
    }
  }

  console.log(`✅ Успешно занесено ${added} реальных организаций без сайта!`);
  console.log(`📍 Минск: 15 лидов | Могилёв: 17 лидов`);
}

