const enrichedLeads = realLeads.map((l, index) => {
  const cleanPhone = (l.phonePrimary || '').replace(/[^0-9]/g, '');
  const tgLink = `https://t.me/+${cleanPhone}`;
  const phoneLink = `tel:${l.phonePrimary.replace(/[\s-]/g, '')}`;
  // Direct Yandex Maps URL with clean encoding
  const yandexMapsUrl = `https://yandex.ru/maps/?text=${encodeURIComponent(l.cityName + ', ' + l.name + ', ' + l.address)}`;
  
  return {
    id: index + 1,
    ...l,
    hasRealWebsite: false,
    telegram: cleanPhone,
    tgLink,
    phoneLink,
    rawWebsite: `https://instagram.com/${l.instagram}/`,
    crmStatus: 'new',
    yandexMapsUrl
  };
});

